#!/usr/bin/env python3
"""Telangana demo scheme rows for scheme_engine.scheme (37 of the 43 listed schemes).

Reads state-packs/TG/schemes.csv for the scheme names and seed_data/telangana/scheme_rules_tg.csv for the demo rules.
THE RULES ARE DEMO VALUES. Every description carries a marker; verify each scheme against its current G.O. before real use
(see state-packs/TG/schemes_verification.csv).

    python3 seed_data/telangana/seed_schemes_tg.py > /tmp/tg_schemes.sql
    psql -d citizen_db -v ON_ERROR_STOP=1 -f /tmp/tg_schemes.sql
"""
import csv, json, sys, uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NS = uuid.UUID("7e1c0a55-0000-4000-8000-0000000000a7")      # fixed namespace -> stable scheme ids
MARK = " [Demo eligibility values, not yet verified.]"


def q(v):
    return "NULL" if v in (None, "") else "'" + str(v).replace("'", "''") + "'"


def conds(spec):
    """'occupation:IN:farmer|education:>=:GRADUATE' -> JSON list of {field, operator, value}."""
    if not spec:
        return None
    items = [dict(zip(("field", "operator", "value"), part.split(":", 2))) for part in spec.split("|")]
    return json.dumps(items)


def n(v):
    return "NULL" if v in (None, "") else str(int(v))


names = {r["code"]: r["name_en"] for r in csv.DictReader(open(ROOT / "state-packs/TG/schemes.csv", encoding="utf-8"))}
rules = list(csv.DictReader(open(ROOT / "seed_data/telangana/scheme_rules_tg.csv", encoding="utf-8")))
missing = [r["code"] for r in rules if r["code"] not in names]
if missing:
    sys.exit(f"codes not in schemes.csv: {missing}")

out = sys.stdout
out.write("-- Telangana demo schemes (generated by seed_data/telangana/seed_schemes_tg.py)\n")
out.write("SELECT set_config('app.state_code', 'TG', false);\nSET search_path TO scheme_engine;\n")
out.write("INSERT INTO scheme (id, name, description, department, benefit_type, benefit_value, income_ceiling, eligible_castes,\n"
          "                    min_age, max_age, gender, district_scope, valid_from, valid_to, is_active, category, created_by, created_at, extra_conditions)\nVALUES\n")
rows = []
for r in rules:
    name = names[r["code"]].removeprefix("Telangana ").strip()
    sid = uuid.uuid5(NS, r["code"])
    rows.append(f"('{sid}', {q(name)}, {q(r['description'] + MARK)}, {q(r['department'])}, {q(r['benefit_type'])}, {q(r['benefit_value'])}, "
                f"{n(r['income_ceiling'])}, {q(r['eligible_castes'])}, {n(r['min_age'])}, {n(r['max_age'])}, {q(r['gender'] or 'ANY')}, 'Telangana', "
                f"'2024-01-01', '2030-12-31', true, {q(r['category'])}, 'seed-tg-demo', NOW(), {q(conds(r['extra_conditions']))})")
out.write(",\n".join(rows))
out.write("\nON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, description = EXCLUDED.description, department = EXCLUDED.department,\n"
          "  benefit_type = EXCLUDED.benefit_type, benefit_value = EXCLUDED.benefit_value, income_ceiling = EXCLUDED.income_ceiling,\n"
          "  eligible_castes = EXCLUDED.eligible_castes, min_age = EXCLUDED.min_age, max_age = EXCLUDED.max_age, gender = EXCLUDED.gender,\n"
          "  district_scope = EXCLUDED.district_scope, category = EXCLUDED.category, extra_conditions = EXCLUDED.extra_conditions, is_active = true;\n")
print(f"-- {len(rows)} schemes", file=sys.stderr)
